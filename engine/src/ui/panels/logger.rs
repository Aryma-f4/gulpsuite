//! Logger: every transaction and every other protocol the listeners see, split the way Gulp splits it.

use eframe::egui::Ui;

use super::{empty_state, heading};
use crate::ui::app::App;

/// One captured DNS exchange.
#[derive(Clone, Debug)]
pub struct DnsEntry {
    pub question: String,
    pub kind: u16,
    pub answers: Vec<String>,
    pub server: String,
}

/// One captured SMTP message.
#[derive(Clone, Debug)]
pub struct SmtpEntry {
    pub direction: String,
    pub from: String,
    pub to: Vec<String>,
    pub subject: String,
    pub body: String,
}

#[derive(Clone)]
pub struct LoggerPanel {
    pub filter: String,
    pub only_errors: bool,
    /// Ports the DNS and SMTP listeners are bound to, once started.
    pub dns_port: Option<u16>,
    pub smtp_port: Option<u16>,
    /// Set by the view when the operator asks for capture to start.
    pub dns_start: bool,
    pub smtp_start: bool,
    /// Set by the view when the operator asks for capture to stop.
    pub dns_stop: bool,
    pub smtp_stop: bool,
    /// The history row the operator has selected, so its message can be shown below the table.
    pub selected: Option<usize>,
    pub sort_column: Option<usize>,
    pub sort_ascending: bool,
    pub table_height: f32,
    pub detail_height: f32,
    pub split_ratio: f32,
    pub req_fmt_mode: usize,
    pub resp_fmt_mode: usize,
    pub req_wrap: bool,
    pub resp_wrap: bool,
    pub req_np: bool,
    pub resp_np: bool,
}

impl Default for LoggerPanel {
    fn default() -> Self {
        Self {
            filter: String::new(),
            only_errors: false,
            dns_port: None,
            smtp_port: None,
            dns_start: false,
            smtp_start: false,
            dns_stop: false,
            smtp_stop: false,
            selected: None,
            sort_column: None,
            sort_ascending: true,
            table_height: 240.0,
            detail_height: 260.0,
            split_ratio: 0.5,
            req_fmt_mode: 0,
            resp_fmt_mode: 0,
            req_wrap: true,
            resp_wrap: true,
            req_np: false,
            resp_np: false,
        }
    }
}

pub fn draw(app: &mut App, ui: &mut Ui) {
    match app.view {
        0 => http(app, ui),
        1 => super::websocket::draw(app, ui, "Logger"),
        2 => dns(app, ui),
        _ => email(app, ui),
    }
}

pub fn draw_http_log(app: &mut App, ui: &mut Ui) {
    http(app, ui);
}

fn http(app: &mut App, ui: &mut Ui) {
    let theme = app.theme.clone();
    // Gulp names the tool in its tab and the sub-tab below it, so a panel heading would repeat
    // it; the sub-tab row already says which log this is.

    ui.horizontal(|ui| {
        let (funnel, _) = ui.allocate_exact_size(
            eframe::egui::Vec2::splat(14.0),
            eframe::egui::Sense::hover(),
        );
        crate::ui::icons::paint(
            ui.painter(),
            funnel,
            theme.color("ui.icon.default"),
            crate::ui::icons::Glyph::Funnel,
        );
        ui.label("Capture filter:");
        ui.text_edit_singleline(&mut app.panels.logger.filter);
        ui.checkbox(&mut app.panels.logger.only_errors, "errors only");
        ui.with_layout(
            eframe::egui::Layout::right_to_left(eframe::egui::Align::Center),
            |ui| {
                ui.label(
                    eframe::egui::RichText::new("Logging on").color(theme.color("ui.text.body")),
                );
            },
        );
    });

    let filter = app.panels.logger.filter.to_lowercase();
    let errors_only = app.panels.logger.only_errors;
    // Rows are indexed from the end, because the table is shown newest first.
    let mut rows: Vec<(usize, crate::ui::app::Transaction)> = app
        .log
        .iter()
        .enumerate()
        .rev()
        .filter(|(_, tx)| !errors_only || tx.status >= 400 || tx.status == 0)
        .filter(|(_, tx)| {
            filter.is_empty()
                || tx.target.to_lowercase().contains(&filter)
                || tx.method.to_lowercase().contains(&filter)
                || tx.status.to_string().contains(&filter)
                || tx.request.to_lowercase().contains(&filter)
                || tx.response.to_lowercase().contains(&filter)
        })
        .map(|(index, tx)| (index, tx.clone()))
        .collect();

    if rows.is_empty() {
        let (learn, _) = empty_state(
            ui,
            &theme,
            if app.log.is_empty() { "Logger is empty" } else { "No matching traffic" },
            if app.log.is_empty() {
                "Logger displays the history of all HTTP traffic sent between Gulp's tools and your \
                 target applications. This includes requests generated by extensions."
            } else {
                "No retained HTTP traffic matches the current filters. Change the capture filter or turn off errors only."
            },
            true,
            None,
        );
        if learn {
            app.status =
                "Logger: HTTP traffic across Proxy, Repeater, Intruder, and Scanner appears here"
                    .into();
        }
        return;
    }

    if let Some(col) = app.panels.logger.sort_column {
        let asc = app.panels.logger.sort_ascending;
        rows.sort_by(|a, b| {
            let ord = match col {
                0 => a.0.cmp(&b.0),
                1 => a.1.method.cmp(&b.1.method),
                2 => a.1.target.cmp(&b.1.target),
                3 => a.1.status.cmp(&b.1.status),
                4 => a.1.bytes.cmp(&b.1.bytes),
                5 => a.1.host_url().cmp(&b.1.host_url()),
                _ => a.0.cmp(&b.0),
            };
            if asc { ord } else { ord.reverse() }
        });
    }

    if app.panels.logger.selected.is_none()
        || !rows
            .iter()
            .any(|(idx, _)| Some(*idx) == app.panels.logger.selected)
    {
        app.panels.logger.selected = rows.first().map(|(idx, _)| *idx);
    }

    let table_h = if app.panels.logger.selected.is_some() {
        app.panels
            .logger
            .table_height
            .min((ui.available_height() * 0.44).max(120.0))
    } else {
        (ui.available_height() - 36.0).max(app.panels.logger.table_height)
    };
    ui.add_space(4.0);
    {
        use eframe::egui::{self, Align2, Color32, FontId, Rect, Sense, Stroke, Vec2, pos2};
        let total_w = ui.available_width().max(420.0);
        let c_num = 54.0_f32;
        let c_method = 74.0_f32;
        let c_status = 68.0_f32;
        let c_bytes = 88.0_f32;
        let rem = (total_w - c_num - c_method - c_status - c_bytes).max(160.0);
        let c_host = (rem * 0.28).clamp(120.0, 320.0);
        let c_target = (rem - c_host).max(120.0);
        let col_widths = [c_num, c_method, c_target, c_status, c_bytes, c_host];
        let col_names = ["#", "Method", "Target", "Status", "Bytes", "Host"];
        let border_col = theme.color("ui.border.1");

        egui::Frame::new()
            .fill(theme.color("ui.background.0"))
            .stroke(Stroke::new(1.0, border_col))
            .corner_radius(4.0)
            .show(ui, |ui| {
                ui.spacing_mut().item_spacing = Vec2::ZERO;
                let (hdr_rect, _) =
                    ui.allocate_exact_size(Vec2::new(total_w, 26.0), Sense::hover());
                ui.painter()
                    .rect_filled(hdr_rect, 0.0, theme.color("ui.background.1"));
                let mut hx = hdr_rect.left();
                for (col_idx, name) in col_names.iter().enumerate() {
                    let cell_r =
                        Rect::from_min_size(pos2(hx, hdr_rect.top()), Vec2::new(col_widths[col_idx], 26.0));
                    let resp = ui.interact(
                        cell_r,
                        ui.id().with(("logger-hdr-col", col_idx)),
                        Sense::click(),
                    );
                    let active = app.panels.logger.sort_column == Some(col_idx);
                    let label_text = if active {
                        if app.panels.logger.sort_ascending {
                            format!("{name} ▲")
                        } else {
                            format!("{name} ▼")
                        }
                    } else {
                        (*name).to_string()
                    };
                    resp.widget_info(|| {
                        egui::WidgetInfo::labeled(egui::WidgetType::SelectableLabel, true, &label_text)
                    });
                    if resp.hovered() {
                        ui.painter()
                            .rect_filled(cell_r, 0.0, theme.color("ui.background.3"));
                    }
                    ui.painter().text(
                        pos2(cell_r.left() + 8.0, cell_r.center().y),
                        Align2::LEFT_CENTER,
                        &label_text,
                        FontId::proportional(11.5),
                        if active {
                            theme.color("ui.icon.link")
                        } else {
                            theme.color("ui.text.header")
                        },
                    );
                    if col_idx + 1 < col_names.len() {
                        ui.painter().vline(
                            cell_r.right(),
                            hdr_rect.y_range(),
                            Stroke::new(1.0, border_col),
                        );
                    }
                    if resp.clicked() {
                        if app.panels.logger.sort_column == Some(col_idx) {
                            if app.panels.logger.sort_ascending {
                                app.panels.logger.sort_ascending = false;
                            } else {
                                app.panels.logger.sort_column = None;
                                app.panels.logger.sort_ascending = true;
                            }
                        } else {
                            app.panels.logger.sort_column = Some(col_idx);
                            app.panels.logger.sort_ascending = true;
                        }
                    }
                    hx = cell_r.right();
                }
                ui.painter()
                    .hline(hdr_rect.x_range(), hdr_rect.bottom(), Stroke::new(1.0, border_col));

                let row_h = 23.0_f32;
                egui::ScrollArea::vertical()
                    .id_salt("logger-table-scroll")
                    .max_height((table_h - 28.0).max(88.0))
                    .auto_shrink([false, false])
                    .show_rows(ui, row_h, rows.len(), |ui, range| {
                        ui.spacing_mut().item_spacing = Vec2::ZERO;
                        for (offset, (index, tx)) in rows[range.clone()].iter().enumerate() {
                            let row_ord = range.start + offset;
                            let selected = app.panels.logger.selected == Some(*index);
                            ui.push_id(("logger-row", *index), |ui| {
                                let (row_rect, row_resp) =
                                    ui.allocate_exact_size(Vec2::new(total_w, row_h), Sense::click());
                                let hovered = row_resp.hovered();
                                let row_fill = if selected {
                                    if theme.dark {
                                        Color32::from_rgb(0x28, 0x45, 0x66)
                                    } else {
                                        Color32::from_rgb(0xCF, 0xE2, 0xF8)
                                    }
                                } else if hovered {
                                    theme.color("ui.background.3")
                                } else if row_ord % 2 == 1 {
                                    theme.color("ui.background.1")
                                } else {
                                    theme.color("ui.background.0")
                                };
                                ui.painter().rect_filled(row_rect, 0.0, row_fill);

                                let host_full = tx.host_url();
                                let cells = [
                                    format!("{}", index + 1),
                                    tx.method.clone(),
                                    tx.target.clone(),
                                    if tx.status == 0 {
                                        String::new()
                                    } else {
                                        tx.status.to_string()
                                    },
                                    tx.bytes.to_string(),
                                    host_full.clone(),
                                ];
                                let mut cx = row_rect.left();
                                for (col_idx, text_val) in cells.iter().enumerate() {
                                    let cell_r = Rect::from_min_size(
                                        pos2(cx, row_rect.top()),
                                        Vec2::new(col_widths[col_idx], row_h),
                                    );
                                    let clip_r = cell_r.shrink2(Vec2::new(7.0, 0.0)).intersect(ui.clip_rect());
                                    let fg = if selected && theme.dark {
                                        Color32::WHITE
                                    } else if col_idx == 1 && tx.method != "GET" {
                                        theme.color("ui.icon.link")
                                    } else if col_idx == 3 {
                                        match tx.status {
                                            200..=299 => Color32::from_rgb(0x2E, 0xA0, 0x43),
                                            300..=399 => Color32::from_rgb(0x38, 0x8B, 0xFD),
                                            400..=499 => Color32::from_rgb(0xD2, 0x99, 0x22),
                                            500..=599 => Color32::from_rgb(0xF8, 0x51, 0x49),
                                            _ => theme.color("ui.text.body"),
                                        }
                                    } else {
                                        theme.color("ui.text.body")
                                    };
                                    ui.painter().with_clip_rect(clip_r).text(
                                        pos2(cell_r.left() + 8.0, cell_r.center().y),
                                        Align2::LEFT_CENTER,
                                        text_val,
                                        FontId::proportional(11.8),
                                        fg,
                                    );
                                    let max_chars = ((col_widths[col_idx] - 16.0) / 6.5).max(8.0) as usize;
                                    if (col_idx == 2 || col_idx == 5) && text_val.chars().count() > max_chars {
                                        let cell_hover = ui.interact(
                                            cell_r,
                                            ui.id().with(("cell-tip", col_idx)),
                                            Sense::click(),
                                        );
                                        if cell_hover.clicked() || cell_hover.secondary_clicked() {
                                            app.panels.logger.selected = Some(*index);
                                        }
                                        app.context_menu(&cell_hover, *index);
                                        cell_hover.on_hover_text(text_val);
                                    }
                                    cx = cell_r.right();
                                }
                                if row_resp.clicked() || row_resp.secondary_clicked() {
                                    app.panels.logger.selected = Some(*index);
                                }
                                app.context_menu(&row_resp, *index);
                            });
                        }
                    });
            });
    }

    super::horizontal_resize_handle(
        ui,
        &theme,
        "logger-table-resize",
        &mut app.panels.logger.table_height,
        120.0,
        540.0,
        240.0,
    );

    let selected = app.panels.logger.selected;
    if let Some(tx) = selected.and_then(|index| app.log.get(index).cloned()) {
        let detail_h = (ui.available_height() - 4.0).max(160.0);
        let mut ratio = app.panels.logger.split_ratio;
        super::vertical_split(
            ui,
            &theme,
            "logger-req-resp-split",
            &mut ratio,
            detail_h,
            |side, ui| {
                if side == 0 {
                    super::gulp_message_formatter_bar(
                        ui,
                        &theme,
                        "logger-req-fmt",
                        "Request",
                        &mut app.panels.logger.req_fmt_mode,
                        false,
                        &mut app.panels.logger.req_wrap,
                        &mut app.panels.logger.req_np,
                    );
                    let r = super::gulp_numbered_message_view_wrapped(
                        ui,
                        &theme,
                        "logger-req",
                        detail_h - 46.0,
                        &tx.request,
                        app.panels.logger.req_fmt_mode,
                        app.panels.logger.req_np,
                        app.panels.logger.req_wrap,
                    );
                    super::attach_message_context_menu(
                        app,
                        &r,
                        &tx.target,
                        &tx.request,
                        &tx.response,
                    );
                } else {
                    super::gulp_message_formatter_bar(
                        ui,
                        &theme,
                        "logger-resp-fmt",
                        "Response",
                        &mut app.panels.logger.resp_fmt_mode,
                        true,
                        &mut app.panels.logger.resp_wrap,
                        &mut app.panels.logger.resp_np,
                    );
                    let r = super::gulp_numbered_message_view_wrapped(
                        ui,
                        &theme,
                        "logger-resp",
                        detail_h - 46.0,
                        &tx.response,
                        app.panels.logger.resp_fmt_mode,
                        app.panels.logger.resp_np,
                        app.panels.logger.resp_wrap,
                    );
                    super::attach_message_context_menu(
                        app,
                        &r,
                        &tx.target,
                        &tx.request,
                        &tx.response,
                    );
                }
            },
        );
        app.panels.logger.split_ratio = ratio;
    }
}

fn dns(app: &mut App, ui: &mut Ui) {
    let theme = app.theme.clone();
    heading(ui, &theme, "DNS");
    ui.horizontal(|ui| {
        if app.panels.logger.dns_port.is_none() {
            if ui.button("Start capture").clicked() {
                app.panels.logger.dns_start = true;
            }
        } else if ui.button("Stop capture").clicked() {
            app.panels.logger.dns_port = None;
            app.panels.logger.dns_stop = true;
        }
        if let Some(port) = app.panels.logger.dns_port {
            ui.label(format!("listening on 127.0.0.1:{port} udp"));
        }
    });

    if app.dns_log.is_empty() {
        let (learn, _) = empty_state(
            ui,
            &theme,
            "DNS log is empty",
            "Start the local DNS listener above and send queries to record DNS exchanges here.",
            true,
            None,
        );
        if learn {
            app.status = "Logger DNS: click Start capture to bind a local UDP DNS listener".into();
        }
        return;
    }
    eframe::egui::ScrollArea::vertical()
        .stick_to_bottom(true)
        .max_height(320.0)
        .show(ui, |ui| {
            eframe::egui::Grid::new("dns-grid")
                .num_columns(3)
                .striped(true)
                .show(ui, |ui| {
                    for name in ["Question", "Type", "Server"] {
                        ui.label(
                            eframe::egui::RichText::new(name)
                                .strong()
                                .color(theme.color("ui.text.body")),
                        );
                    }
                    ui.end_row();
                    for entry in app.dns_log.iter().rev() {
                        ui.label(eframe::egui::RichText::new(&entry.question).monospace());
                        ui.label(crate::dns::kind_name(entry.kind));
                        ui.label(&entry.server);
                        ui.end_row();
                    }
                });
        });
}

fn email(app: &mut App, ui: &mut Ui) {
    let theme = app.theme.clone();
    heading(ui, &theme, "SMTP");
    ui.horizontal(|ui| {
        if app.panels.logger.smtp_port.is_none() {
            if ui.button("Start capture").clicked() {
                app.panels.logger.smtp_start = true;
            }
        } else if ui.button("Stop capture").clicked() {
            app.panels.logger.smtp_port = None;
            app.panels.logger.smtp_stop = true;
        }
        if let Some(port) = app.panels.logger.smtp_port {
            ui.label(format!("listening on 127.0.0.1:{port}"));
        }
    });

    if app.smtp_log.is_empty() {
        let (learn, _) = empty_state(
            ui,
            &theme,
            "SMTP log is empty",
            "Start the local SMTP listener above and send messages to record SMTP traffic here.",
            true,
            None,
        );
        if learn {
            app.status = "Logger SMTP: click Start capture to bind a local TCP SMTP listener".into();
        }
        return;
    }
    let mut expanded: Option<usize> = None;
    eframe::egui::ScrollArea::vertical()
        .stick_to_bottom(true)
        .max_height(320.0)
        .show(ui, |ui| {
            for (index, message) in app.smtp_log.iter().enumerate().rev() {
                let head = format!("{} — {} → {}", message.subject, message.from, message.to.join(", "));
                if eframe::egui::CollapsingHeader::new(head)
                    .default_open(expanded == Some(index))
                    .show(ui, |ui| {
                        ui.label(eframe::egui::RichText::new(message.body.clone()).monospace());
                    })
                    .header_response.clicked()
                {
                    expanded = Some(index);
                }
            }
        });
}
