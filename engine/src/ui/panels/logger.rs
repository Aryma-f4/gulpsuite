//! Logger: every transaction and every other protocol the listeners see, split the way Burp splits it.

use eframe::egui::Ui;

use super::{empty_state, heading};
use crate::ui::app::App;

/// One captured DNS exchange.
#[derive(Clone, Debug)]
pub struct DnsEntry {
    pub question: String,
    pub kind: u16,
    pub answers: Vec<String>,
    pub server: String,
}

/// One captured SMTP message.
#[derive(Clone, Debug)]
pub struct SmtpEntry {
    pub direction: String,
    pub from: String,
    pub to: Vec<String>,
    pub subject: String,
    pub body: String,
}

#[derive(Clone)]
pub struct LoggerPanel {
    pub filter: String,
    pub only_errors: bool,
    /// Ports the DNS and SMTP listeners are bound to, once started.
    pub dns_port: Option<u16>,
    pub smtp_port: Option<u16>,
    /// Set by the view when the operator asks for capture to start.
    pub dns_start: bool,
    pub smtp_start: bool,
    /// Set by the view when the operator asks for capture to stop.
    pub dns_stop: bool,
    pub smtp_stop: bool,
    /// The history row the operator has selected, so its message can be shown below the table.
    pub selected: Option<usize>,
    pub sort_column: Option<usize>,
    pub sort_ascending: bool,
    pub table_height: f32,
    pub detail_height: f32,
    pub split_ratio: f32,
    pub req_fmt_mode: usize,
    pub resp_fmt_mode: usize,
    pub req_wrap: bool,
    pub resp_wrap: bool,
    pub req_np: bool,
    pub resp_np: bool,
}

impl Default for LoggerPanel {
    fn default() -> Self {
        Self {
            filter: String::new(),
            only_errors: false,
            dns_port: None,
            smtp_port: None,
            dns_start: false,
            smtp_start: false,
            dns_stop: false,
            smtp_stop: false,
            selected: None,
            sort_column: None,
            sort_ascending: true,
            table_height: 240.0,
            detail_height: 260.0,
            split_ratio: 0.5,
            req_fmt_mode: 0,
            resp_fmt_mode: 0,
            req_wrap: true,
            resp_wrap: true,
            req_np: false,
            resp_np: false,
        }
    }
}

pub fn draw(app: &mut App, ui: &mut Ui) {
    match app.view {
        0 => http(app, ui),
        1 => super::websocket::draw(app, ui, "Logger"),
        2 => dns(app, ui),
        _ => email(app, ui),
    }
}

fn http(app: &mut App, ui: &mut Ui) {
    let theme = app.theme.clone();
    // Burp names the tool in its tab and the sub-tab below it, so a panel heading would repeat
    // it; the sub-tab row already says which log this is.

    ui.horizontal(|ui| {
        let (funnel, _) = ui.allocate_exact_size(
            eframe::egui::Vec2::splat(14.0),
            eframe::egui::Sense::hover(),
        );
        crate::ui::icons::paint(
            ui.painter(),
            funnel,
            theme.color("ui.icon.default"),
            crate::ui::icons::Glyph::Funnel,
        );
        ui.label("Capture filter:");
        ui.text_edit_singleline(&mut app.panels.logger.filter);
        ui.checkbox(&mut app.panels.logger.only_errors, "errors only");
        ui.with_layout(
            eframe::egui::Layout::right_to_left(eframe::egui::Align::Center),
            |ui| {
                ui.label(
                    eframe::egui::RichText::new("Logging on").color(theme.color("ui.text.body")),
                );
            },
        );
    });

    let filter = app.panels.logger.filter.to_lowercase();
    let errors_only = app.panels.logger.only_errors;
    // Rows are indexed from the end, because the table is shown newest first.
    let mut rows: Vec<(usize, crate::ui::app::Transaction)> = app
        .log
        .iter()
        .cloned()
        .enumerate()
        .rev()
        .take(500)
        .filter(|(_, tx)| !errors_only || tx.status >= 400)
        .filter(|(_, tx)| filter.is_empty() || tx.target.to_lowercase().contains(&filter))
        .collect();

    if rows.is_empty() {
        let (learn, _) = empty_state(
            ui,
            &theme,
            "Logger is empty",
            "Logger displays the history of all HTTP traffic sent between Gulp's tools and your \
             target applications. This includes requests generated by extensions.",
            true,
            None,
        );
        if learn {
            app.status =
                "Logger: HTTP traffic across Proxy, Repeater, Intruder, and Scanner appears here"
                    .into();
        }
        return;
    }

    if let Some(col) = app.panels.logger.sort_column {
        let asc = app.panels.logger.sort_ascending;
        rows.sort_by(|a, b| {
            let ord = match col {
                0 => a.0.cmp(&b.0),
                1 => a.1.method.cmp(&b.1.method),
                2 => a.1.target.cmp(&b.1.target),
                3 => a.1.status.cmp(&b.1.status),
                4 => a.1.bytes.cmp(&b.1.bytes),
                5 => a.1.host_url().cmp(&b.1.host_url()),
                _ => a.0.cmp(&b.0),
            };
            if asc { ord } else { ord.reverse() }
        });
    }

    let table_h = if app.panels.logger.selected.is_some() {
        app.panels
            .logger
            .table_height
            .min((ui.available_height() * 0.44).max(120.0))
    } else {
        (ui.available_height() - 36.0).max(app.panels.logger.table_height)
    };
    eframe::egui::ScrollArea::vertical()
        .id_salt("logger-table-scroll")
        .max_height(table_h)
        .stick_to_bottom(true)
        .show(ui, |ui| {
            eframe::egui::Grid::new("logger-grid")
                .num_columns(6)
                .striped(true)
                .show(ui, |ui| {
                    for (col_idx, name) in ["#", "Method", "Target", "Status", "Bytes", "Host"].iter().enumerate() {
                        let active = app.panels.logger.sort_column == Some(col_idx);
                        let label_text = if active {
                            if app.panels.logger.sort_ascending {
                                format!("{name} ▲")
                            } else {
                                format!("{name} ▼")
                            }
                        } else {
                            (*name).to_string()
                        };
                        if ui
                            .selectable_label(
                                active,
                                eframe::egui::RichText::new(label_text)
                                    .strong()
                                    .color(theme.color("ui.text.body")),
                            )
                            .clicked()
                        {
                            if app.panels.logger.sort_column == Some(col_idx) {
                                if app.panels.logger.sort_ascending {
                                    app.panels.logger.sort_ascending = false;
                                } else {
                                    app.panels.logger.sort_column = None;
                                    app.panels.logger.sort_ascending = true;
                                }
                            } else {
                                app.panels.logger.sort_column = Some(col_idx);
                                app.panels.logger.sort_ascending = true;
                            }
                        }
                    }
                    ui.end_row();
                    for (index, tx) in rows.iter() {
                        ui.push_id(("logger-row", *index), |ui| {
                            let selected = app.panels.logger.selected == Some(*index);
                            let c_idx = ui.selectable_label(selected, format!("{}", index + 1));
                            let text = if selected {
                                eframe::egui::RichText::new(&tx.method)
                                    .color(theme.color("ui.icon.link"))
                            } else {
                                eframe::egui::RichText::new(&tx.method)
                            };
                            let short_target = if tx.target.chars().count() > 44 {
                                let mut s: String = tx.target.chars().take(43).collect();
                                s.push('…');
                                s
                            } else {
                                tx.target.clone()
                            };
                            let host_full = tx.host_url();
                            let short_host = if host_full.chars().count() > 28 {
                                let mut s: String = host_full.chars().take(27).collect();
                                s.push('…');
                                s
                            } else {
                                host_full.clone()
                            };
                            let c_method = ui.selectable_label(selected, text);
                            let c_target = ui
                                .selectable_label(selected, short_target)
                                .on_hover_text(&tx.target);
                            let c_status = ui.selectable_label(selected, tx.status.to_string());
                            let c_bytes = ui.selectable_label(selected, tx.bytes.to_string());
                            let c_host = ui
                                .selectable_label(selected, short_host)
                                .on_hover_text(&host_full);
                            for cell in [&c_idx, &c_method, &c_target, &c_status, &c_bytes, &c_host]
                            {
                                if cell.clicked() || cell.secondary_clicked() {
                                    app.panels.logger.selected = Some(*index);
                                }
                                app.context_menu(cell, *index);
                            }
                        });
                        ui.end_row();
                    }
                });
        });

    super::horizontal_resize_handle(
        ui,
        &theme,
        "logger-table-resize",
        &mut app.panels.logger.table_height,
        120.0,
        540.0,
        240.0,
    );

    let selected = app.panels.logger.selected;
    if let Some(tx) = selected.and_then(|index| app.log.get(index).cloned()) {
        let detail_h = (ui.available_height() - 16.0).max(app.panels.logger.detail_height.min(180.0));
        let mut ratio = app.panels.logger.split_ratio;
        super::vertical_split(
            ui,
            &theme,
            "logger-req-resp-split",
            &mut ratio,
            detail_h,
            |side, ui| {
                if side == 0 {
                    super::burp_message_formatter_bar(
                        ui,
                        &theme,
                        "logger-req-fmt",
                        "Request",
                        &mut app.panels.logger.req_fmt_mode,
                        false,
                        &mut app.panels.logger.req_wrap,
                        &mut app.panels.logger.req_np,
                    );
                    let r = super::burp_numbered_message_view_wrapped(
                        ui,
                        &theme,
                        "logger-req",
                        detail_h - 48.0,
                        &tx.request,
                        app.panels.logger.req_fmt_mode,
                        app.panels.logger.req_np,
                        app.panels.logger.req_wrap,
                    );
                    super::attach_message_context_menu(
                        app,
                        &r,
                        &tx.target,
                        &tx.request,
                        &tx.response,
                    );
                } else {
                    super::burp_message_formatter_bar(
                        ui,
                        &theme,
                        "logger-resp-fmt",
                        "Response",
                        &mut app.panels.logger.resp_fmt_mode,
                        true,
                        &mut app.panels.logger.resp_wrap,
                        &mut app.panels.logger.resp_np,
                    );
                    let r = super::burp_numbered_message_view_wrapped(
                        ui,
                        &theme,
                        "logger-resp",
                        detail_h - 48.0,
                        &tx.response,
                        app.panels.logger.resp_fmt_mode,
                        app.panels.logger.resp_np,
                        app.panels.logger.resp_wrap,
                    );
                    super::attach_message_context_menu(
                        app,
                        &r,
                        &tx.target,
                        &tx.request,
                        &tx.response,
                    );
                }
            },
        );
        app.panels.logger.split_ratio = ratio;
        super::horizontal_resize_handle(
            ui,
            &theme,
            "logger-detail-resize",
            &mut app.panels.logger.detail_height,
            120.0,
            600.0,
            260.0,
        );
    }
}

fn dns(app: &mut App, ui: &mut Ui) {
    let theme = app.theme.clone();
    heading(ui, &theme, "DNS");
    ui.horizontal(|ui| {
        if app.panels.logger.dns_port.is_none() {
            if ui.button("Start capture").clicked() {
                app.panels.logger.dns_start = true;
            }
        } else if ui.button("Stop capture").clicked() {
            app.panels.logger.dns_port = None;
            app.panels.logger.dns_stop = true;
        }
        if let Some(port) = app.panels.logger.dns_port {
            ui.label(format!("listening on 127.0.0.1:{port} udp"));
        }
    });

    if app.dns_log.is_empty() {
        let (learn, _) = empty_state(
            ui,
            &theme,
            "DNS log is empty",
            "Start the local DNS listener above and send queries to record DNS exchanges here.",
            true,
            None,
        );
        if learn {
            app.status = "Logger DNS: click Start capture to bind a local UDP DNS listener".into();
        }
        return;
    }
    eframe::egui::ScrollArea::vertical()
        .stick_to_bottom(true)
        .max_height(320.0)
        .show(ui, |ui| {
            eframe::egui::Grid::new("dns-grid")
                .num_columns(3)
                .striped(true)
                .show(ui, |ui| {
                    for name in ["Question", "Type", "Server"] {
                        ui.label(
                            eframe::egui::RichText::new(name)
                                .strong()
                                .color(theme.color("ui.text.body")),
                        );
                    }
                    ui.end_row();
                    for entry in app.dns_log.iter().rev() {
                        ui.label(eframe::egui::RichText::new(&entry.question).monospace());
                        ui.label(crate::dns::kind_name(entry.kind));
                        ui.label(&entry.server);
                        ui.end_row();
                    }
                });
        });
}

fn email(app: &mut App, ui: &mut Ui) {
    let theme = app.theme.clone();
    heading(ui, &theme, "SMTP");
    ui.horizontal(|ui| {
        if app.panels.logger.smtp_port.is_none() {
            if ui.button("Start capture").clicked() {
                app.panels.logger.smtp_start = true;
            }
        } else if ui.button("Stop capture").clicked() {
            app.panels.logger.smtp_port = None;
            app.panels.logger.smtp_stop = true;
        }
        if let Some(port) = app.panels.logger.smtp_port {
            ui.label(format!("listening on 127.0.0.1:{port}"));
        }
    });

    if app.smtp_log.is_empty() {
        let (learn, _) = empty_state(
            ui,
            &theme,
            "SMTP log is empty",
            "Start the local SMTP listener above and send messages to record SMTP traffic here.",
            true,
            None,
        );
        if learn {
            app.status = "Logger SMTP: click Start capture to bind a local TCP SMTP listener".into();
        }
        return;
    }
    let mut expanded: Option<usize> = None;
    eframe::egui::ScrollArea::vertical()
        .stick_to_bottom(true)
        .max_height(320.0)
        .show(ui, |ui| {
            for (index, message) in app.smtp_log.iter().enumerate().rev() {
                let head = format!("{} — {} → {}", message.subject, message.from, message.to.join(", "));
                if eframe::egui::CollapsingHeader::new(head)
                    .default_open(expanded == Some(index))
                    .show(ui, |ui| {
                        ui.label(eframe::egui::RichText::new(message.body.clone()).monospace());
                    })
                    .header_response.clicked()
                {
                    expanded = Some(index);
                }
            }
        });
}
